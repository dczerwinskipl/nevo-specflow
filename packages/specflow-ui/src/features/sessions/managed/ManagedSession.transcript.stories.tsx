/** A question above the Composer, on an opaque surface the transcript never shows through. */
const opaqueNotice = async ({ canvasElement }: { canvasElement: HTMLElement }) => {
  await waitFor(() => {
    const notice = canvasElement.querySelector<HTMLElement>('[data-composer-notice]');
    if (!notice) {
      throw new Error('Expected a notice above the Composer.');
    }

    const background = getComputedStyle(notice).backgroundColor;
    if (/rgba\(.*,\s*0(\.\d+)?\)$/.test(background) || background === 'transparent') {
      throw new Error(`The notice surface is not opaque: ${background}`);
    }
  });
};

