/**
 * `SpecFlow/Screens/Managed Session/Transcript`: an agent step Session read as a whole
 * (full-session.md "Conversation"): the brief as the first message, the agent named once per Turn,
 * its Commentary and tool Work in stages, its answer, one outcome event for a Turn that did not
 * complete, a resumed Turn of the same attempt, and the notices docked above the Composer. Each
 * scenario at a phone and a desktop width.
 */
