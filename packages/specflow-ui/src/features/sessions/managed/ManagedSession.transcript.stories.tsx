/**
 * `SpecFlow/Screens/Managed Session/Transcript`: an agent step Session read as a whole
 * (full-session.md "Conversation"): the brief as the first message, the agent named once per Turn,
 * its Commentary and tool Work in stages, its answer, one outcome event for a Turn that did not
 * complete, a resumed Turn of the same attempt, and the notices docked above the Composer. Each
 * scenario at a phone and a desktop width.
 */
const meta = {
  title: 'SpecFlow/Screens/Managed Session/Transcript',
  component: ManagedSession,
  parameters: { layout: 'fullscreen' },
  decorators: [
    (Story) => (
      <Environment>
        <Story />
      </Environment>
    ),
  ],
  args: {
    sessionId: fixtureSessionId,
    owner: 'transcript-story',
    api: transcriptApi(normalRunSnapshot()),
    sessionContext: genericSpecLevelContext(),
    onOpenSpecification: fn(),
    onOpenDocuments: fn(),
    onReviewChanges: fn(),
  },
} satisfies Meta<typeof ManagedSession>;
export default meta;
type Story = StoryObj<typeof meta>;

/** The brief reads as the first message, generated by SpecFlow; the agent is named once. */
const normalPlay: Story['play'] = async ({ canvasElement }) => {
  const canvas = within(canvasElement);
  await canvas.findByText('Wygenerowane przez SpecFlow');
  const brief = canvasElement.querySelector<HTMLElement>('[data-entry-origin]')!;
  await expect(within(brief).getByText('Design the solution')).toBeVisible();
  await expect(
    within(brief).getByText(/Reconcile the Specification with the architecture/),
  ).toBeVisible();
  await expect(canvasElement.querySelectorAll('[data-agent-identity]')).toHaveLength(1);
  await expect(canvasElement.querySelectorAll('[data-work-stage]')).toHaveLength(2);
  // No raw brief text in the conversation.
  await expect(canvas.queryByText(/untrusted/)).toBeNull();
};

export const NormalRunMobile: Story = {
  tags: ['contract'],
  args: { api: transcriptApi(normalRunSnapshot()) },
  globals: NARROW_VIEWPORT,
  play: normalPlay,
};
export const NormalRunDesktop: Story = {
  tags: ['contract'],
  args: { api: transcriptApi(normalRunSnapshot()) },
  globals: WIDE_VIEWPORT,
  play: normalPlay,
};

